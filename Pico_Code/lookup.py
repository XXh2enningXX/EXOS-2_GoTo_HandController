# Automatisch generierte Lookup-Tabelle (12-Byte-Frames) für HBX-Simulator

def hx(s: str) -> bytes:
    """Konvertiert Hex-String in Bytes"""
    return bytes(int(b, 16) for b in s.split()) if s.strip() else b""

